denominator = (

    np.abs(ts_actual)

    +

    np.abs(lstm_pred)

)


valid = (
    denominator != 0
)

lstm_smape = (

    np.mean(

        2

        *

        np.abs(

            lstm_pred[valid]

            -

            ts_actual[valid]

        )

        /

        denominator[valid]

    )

    * 100

)


model_results.append({

    "Model":
        "LSTM",

    "MAE":
        lstm_mae,

    "RMSE":
        lstm_rmse,

    "R2":
        lstm_r2,

    "MAPE":
        lstm_mape,

    "SMAPE":
        lstm_smape

})


