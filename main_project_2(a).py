lstm_model = Sequential()


lstm_model.add(

    LSTM(

        64,

        return_sequences=True,

        input_shape=(
            sequence_length,
            1
        )

    )

)


lstm_model.add(

    Dropout(0.2)

)


lstm_model.add(

    LSTM(
        32
    )

)


lstm_model.add(

    Dropout(0.2)

)


lstm_model.add(

    Dense(
        16,
        activation="relu"
    )

)


lstm_model.add(

    Dense(1)

)


lstm_model.compile(

    optimizer="adam",

    loss="mse"

)


early_stop = EarlyStopping(

    monitor="val_loss",

    patience=10,

    restore_best_weights=True

)

# ============================================================
# STEP 23: TRAIN LSTM
# ============================================================

history = lstm_model.fit(

    X_lstm,

    y_lstm,

    epochs=100,

    batch_size=32,

    validation_split=0.15,

    callbacks=[
        early_stop
    ],

    verbose=1,

    shuffle=False

)

# ============================================================
